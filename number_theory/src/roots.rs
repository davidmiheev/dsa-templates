//! Integer roots, and `k`-th roots modulo a prime.

use super::dlog::discrete_log_smooth;
use super::{factorize, gcd, mod_inverse, mul_mod, pow_mod, NONE};

/// `floor(sqrt(n))`.
pub fn isqrt(n: u64) -> u64 {
    let mut r = (n as f64).sqrt() as u64;
    while (r as u128) * (r as u128) > n as u128 {
        r -= 1;
    }
    while ((r + 1) as u128) * ((r + 1) as u128) <= n as u128 {
        r += 1;
    }
    r
}

/// Whether `x^k <= a`.
fn pow_le(x: u64, k: u32, a: u64) -> bool {
    let mut r: u128 = 1;
    for _ in 0..k {
        r *= x as u128;
        if r > a as u128 {
            return false;
        }
    }
    true
}

/// `floor(a^(1/k))` for `k >= 1`.
pub fn kth_root(a: u64, k: u32) -> u64 {
    assert!(k >= 1, "k must be positive");
    if k == 1 || a <= 1 {
        return a;
    }
    if k == 2 {
        return isqrt(a);
    }
    if k >= 64 {
        return 1;
    }
    let mut r = (a as f64).powf(1.0 / k as f64) as u64;
    while r > 0 && !pow_le(r, k, a) {
        r -= 1;
    }
    while pow_le(r + 1, k, a) {
        r += 1;
    }
    r
}

/// Some `x` with `x^k = y (mod p)` for the prime `p`, or [`NONE`] if there is none
/// (`0^0 = 1`). The part of the group whose order is coprime to `k` is handled by one power; a
/// discrete logarithm (Pohlig-Hellman, `O(sqrt(q))` for each prime `q | gcd(k, p - 1)`) is only
/// needed for the rest.
///
/// # Panics
/// Panics if `p` is not a prime below `2^32`.
pub fn kth_root_mod(k: u64, y: u64, p: u64) -> u64 {
    assert!(y < p, "y must be reduced modulo p");
    if k == 0 {
        return if y == 1 { 0 } else { NONE };
    }
    if y == 0 || p == 2 {
        return y;
    }
    let n = p - 1;
    // n = n1 * n2, n1 made of the primes dividing k
    let factors = factorize(n);
    let f1: Vec<(u64, u32)> = factors.into_iter().filter(|&(q, _)| k.is_multiple_of(q)).collect();
    let n1: u64 = f1.iter().map(|&(q, e)| q.pow(e)).product();
    let n2 = n / n1;
    // y = u * v with u of order dividing n1 and v of order dividing n2
    let e1 = n2 * mod_inverse(n2 % n1.max(1), n1.max(1)) % n; // 1 mod n1, 0 mod n2
    let u = pow_mod(y, e1, p);
    let v = mul_mod(y, mod_inverse(u, p), p);
    let x2 = if n2 == 1 { 1 } else { pow_mod(v, mod_inverse(k % n2, n2), p) };
    if n1 == 1 {
        return x2;
    }
    // k-th root of u in the cyclic group of order n1, generated by g1
    let g1 = (2..p).map(|a| pow_mod(a, n2, p)).find(|&h| f1.iter().all(|&(q, _)| pow_mod(h, n1 / q, p) != 1)).expect("a generator exists");
    let b = discrete_log_smooth(u, g1, p, &f1);
    let d = gcd(k, n1);
    if !b.is_multiple_of(d) {
        return NONE;
    }
    let m = n1 / d;
    let a = (b / d % m) as u128 * mod_inverse(k / d % m, m) as u128 % m as u128;
    mul_mod(pow_mod(g1, a as u64, p), x2, p)
}
